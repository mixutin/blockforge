// Kindlr Script: Kindlr's text language. Two-way conversion between blocks and text.
import { DEFS, DEF_LIST, argKinds, newBlock } from './blocks.js';
import { LIMITS, LimitError, checkTextSize, validateScripts } from './limits.js';

const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;
const KW = new Map(); // keyword -> [defs]
for (const d of DEF_LIST) {
  if (d.infix || ['var', 'list', 'param', 'call', 'define'].includes(d.op)) continue;
  if (!KW.has(d.kw)) KW.set(d.kw, []); KW.get(d.kw).push(d);
}
const quote = s => JSON.stringify(String(s));
const lit = v => {
  if (v === null || v === undefined) return 'false';
  if (typeof v === 'number') return String(v);
  return /^-?\d+(\.\d+)?$/.test(v) ? v : quote(v);
};
const nameRef = (sig, n) => sig + (IDENT.test(n) ? n : quote(n));

export function exprToText(v, parentPrec = 0, right = false) {
  if (!v || typeof v !== 'object' || !v.op) return lit(v);
  const d = DEFS[v.op];
  if (v.op === 'var') return nameRef('@', v.args[0]);
  if (v.op === 'list') return nameRef('@@', v.args[0]);
  if (v.op === 'param') return IDENT.test(v.args[0]) ? v.args[0] : `param(${quote(v.args[0])})`;
  if (d.infix) {
    const s = `${exprToText(v.args[0], d.prec)} ${d.infix} ${exprToText(v.args[1], d.prec, true)}`;
    return d.prec < parentPrec || (right && d.prec === parentPrec) ? `(${s})` : s;
  }
  if (v.op === 'op_not') { const s = `not ${exprToText(v.args[0], 3)}`; return parentPrec > 3 || right && parentPrec > 0 ? `(${s})` : s; }
  return callText(d.kw, v.args, v.op);
}
const callText = (kw, args, op) => {
  const kinds = op ? argKinds(op) : [];
  const t = args.map((a, i) => {
    const m = kinds[i]?.menu;
    if (m === 'var' && typeof a === 'string') return nameRef('@', a);
    if (m === 'list' && typeof a === 'string') return nameRef('@@', a);
    return exprToText(a);
  });
  return args.length ? `${kw}(${t.join(', ')})` : kw;
};

function stackToText(blocks, ind) { return blocks.map(b => blockToText(b, ind)).join('\n'); }
function bodyText(blocks, ind) { return blocks && blocks.length ? `{\n${stackToText(blocks, ind + '  ')}\n${ind}}` : '{ }'; }
function blockToText(b, ind) {
  const d = DEFS[b.op]; if (!d) return ind + '// unknown block ' + b.op;
  if (b.op === 'call') return ind + `${b.name}(${b.args.map(a => exprToText(a)).join(', ')})`;
  if (d.type === 'reporter' || d.type === 'boolean') return ind + `eval(${exprToText(b)})`;
  let s = ind + callText(d.kw, b.args, b.op);
  if (d.type === 'c') s += ' ' + bodyText(b.body, ind);
  if (d.type === 'cc') s += ' ' + bodyText(b.body, ind) + ' else ' + bodyText(b.body2, ind);
  return s;
}
export function scriptToText(script) {
  const [top, ...rest] = script.blocks; if (!top) return '';
  const d = DEFS[top.op];
  if (top.op === 'define') return `define${top.warp ? '!' : ''} ${top.name}(${(top.params || []).join(', ')}) ${bodyText(rest, '')}`;
  if (d && d.type === 'hat') return `${callText(d.kw, top.args, top.op)} ${bodyText(rest, '')}`;
  return `script ${bodyText(script.blocks, '')}`;
}
export function targetToText(t) {
  const head = `// Kindlr Script for ${t.isStage ? 'the Stage' : 'sprite "' + t.name + '"'} — generated by Kindlr\n`;
  return head + '\n' + t.scripts.map(scriptToText).filter(Boolean).join('\n\n') + '\n';
}

// ---------------- parser ----------------
function tokenize(src) {
  const toks = []; let i = 0, line = 1;
  const push = (t, v) => toks.push({ t, v, line });
  while (i < src.length) {
    const c = src[i];
    if (c === '\n') { line++; i++; continue; }
    if (/\s/.test(c)) { i++; continue; }
    if (c === '/' && src[i + 1] === '/') { while (i < src.length && src[i] !== '\n') i++; continue; }
    if (c === '"') {
      let j = i + 1, s = '';
      while (j < src.length && src[j] !== '"') { if (src[j] === '\\') { const n = src[j + 1]; s += n === 'n' ? '\n' : n; j += 2; } else s += src[j++]; }
      if (j >= src.length) throw new Error(`Line ${line}: unterminated string`);
      push('str', s); i = j + 1; continue;
    }
    if (/[0-9]/.test(c) || (c === '.' && /[0-9]/.test(src[i + 1]))) { const m = /^\d*\.?\d+(e[+-]?\d+)?/i.exec(src.slice(i, i + 400)); push('num', m[0]); i += m[0].length; continue; }
    if (/[A-Za-z_]/.test(c)) { const m = /^[A-Za-z_][A-Za-z0-9_]*/.exec(src.slice(i, i + 200)); push('id', m[0]); i += m[0].length; continue; }
    if (c === '@') { if (src[i + 1] === '@') { push('@@'); i += 2; } else { push('@'); i++; } continue; }
    if (src.startsWith('!=', i) || src.startsWith('==', i) || src.startsWith('<=', i) || src.startsWith('>=', i)) { push('op', src.slice(i, i + 2)); i += 2; continue; }
    if ('(){},!'.includes(c)) { push(c); i++; continue; }
    if ('+-*/%<>='.includes(c)) { push('op', c); i++; continue; }
    throw new Error(`Line ${line}: unexpected character '${c}'`);
  }
  push('eof'); return toks;
}
const INFIX_OBJ = { or: ['op_or', 1], and: ['op_and', 2], '<': ['op_lt', 4], '>': ['op_gt', 4], '=': ['op_eq', 4], '==': ['op_eq', 4], '!=': ['ne', 4], '<=': ['le', 4], '>=': ['ge', 4], '+': ['op_add', 5], '-': ['op_sub', 5], '*': ['op_mul', 6], '/': ['op_div', 6], '%': ['op_mod', 6] };
const INFIX = new Map(Object.entries(INFIX_OBJ));   // Map lookup: tokens like 'constructor' are not operators

export function parseKls(src) {
  checkTextSize(src);
  const toks = tokenize(src); let p = 0; let depth = 0, count = 0;
  const enter = () => { if (++depth > LIMITS.maxDepth) throw new LimitError(`Line ${peek().line}: nesting deeper than ${LIMITS.maxDepth}`); if (++count > LIMITS.maxBlocks) throw new LimitError(`More than ${LIMITS.maxBlocks} blocks`); };
  const peek = (o = 0) => toks[p + o];
  const err = (m, tk = peek()) => { throw new Error(`Line ${tk.line}: ${m}`); };
  const eat = (t, v) => { const tk = peek(); if (tk.t !== t || (v !== undefined && tk.v !== v)) err(`expected ${v || t} but found ${tk.v ?? tk.t}`); p++; return tk; };
  const is = (t, v) => peek().t === t && (v === undefined || peek().v === v);
  const customs = new Map(); // name -> params (pre-scan)
  for (let i = 0; i < toks.length - 1; i++) if (toks[i].t === 'id' && toks[i].v === 'define') {
    let j = i + 1; if (toks[j].t === '!') j++; if (toks[j].t === 'id') customs.set(toks[j].v, true);
  }

  function parseArgs() {
    const args = []; if (!is('(')) return args; eat('(');
    if (!is(')')) { do { args.push(parseExpr(0)); } while (is(',') && eat(',')); }
    eat(')'); return args;
  }
  function parseExpr(minPrec) {
    enter(); try { return parseExpr2(minPrec); } finally { depth--; }
  }
  function parseExpr2(minPrec) {
    let left = parseUnary();
    for (;;) {
      const tk = peek(); const key = tk.t === 'op' ? tk.v : tk.t === 'id' && (tk.v === 'and' || tk.v === 'or') ? tk.v : null;
      if (!key || !INFIX.has(key) || INFIX.get(key)[1] < minPrec) break;
      const [op, prec] = INFIX.get(key); if (prec < minPrec) break; p++;
      const right = parseExpr(prec + 1);
      if (op === 'ne') left = { op: 'op_not', args: [{ op: 'op_eq', args: [left, right] }] };
      else if (op === 'le') left = { op: 'op_not', args: [{ op: 'op_gt', args: [left, right] }] };
      else if (op === 'ge') left = { op: 'op_not', args: [{ op: 'op_lt', args: [left, right] }] };
      else left = { op, args: [left, right] };
    }
    return left;
  }
  function parseUnary() {
    if (is('op', '-')) { p++; const v = parseUnary(); if (typeof v === 'string' && /^\d/.test(v)) return '-' + v; return { op: 'op_sub', args: ['0', v] }; }
    if (is('id', 'not')) { p++; return { op: 'op_not', args: [parseExpr(3)] }; }
    return parsePrimary();
  }
  function parsePrimary() {
    const tk = peek();
    if (tk.t === 'num') { p++; return tk.v; }
    if (tk.t === 'str') { p++; return tk.v; }
    if (tk.t === '(') { p++; const e = parseExpr(0); eat(')'); return e; }
    if (tk.t === '@' || tk.t === '@@') { p++; const n = peek(); if (n.t !== 'id' && n.t !== 'str') err('expected a name after ' + tk.t); p++; return { op: tk.t === '@' ? 'var' : 'list', args: [n.v] }; }
    if (tk.t === 'id') {
      p++;
      if (tk.v === 'false') return { op: 'dt_false', args: [] };
      if (tk.v === 'true') return { op: 'dt_true', args: [] };
      if (tk.v === 'param' && is('(')) { const a = parseArgs(); return { op: 'param', args: [String(a[0])] }; }
      const defs = (KW.get(tk.v) || []).filter(d => d.type === 'reporter' || d.type === 'boolean');
      if (defs.length) return fill(defs[0], parseArgs(), tk);
      if (is('(')) err(`unknown reporter '${tk.v}'`, tk);
      return { op: 'param', args: [tk.v] };
    }
    err(`unexpected ${tk.v ?? tk.t}`);
  }
  function fill(d, args, tk) {
    const kinds = argKinds(d.op);
    if (args.length > kinds.length) err(`'${d.kw}' takes ${kinds.length} argument(s) but got ${args.length}`, tk);
    const b = newBlock(d.op); args.forEach((a, i) => (b.args[i] = a));
    kinds.forEach((k, i) => {
      const v = b.args[i];
      if (k.menu === 'var' && v && v.op === 'var') b.args[i] = v.args[0];
      if (k.menu === 'list' && v && (v.op === 'list' || v.op === 'var')) b.args[i] = v.args[0]; if (k.kind === 'm' && b.args[i] && typeof b.args[i] === 'object') err(`argument ${i + 1} of '${d.kw}' must be a plain value`, tk); });
    return b;
  }
  function parseBody(allowLoneReporter = false) {
    eat('{'); const out = [];
    while (!is('}')) { if (is('eof')) err('missing }'); const tk = peek(); const st = parseStmt();
      if (st && typeof st === 'object' && (DEFS[st.op]?.type === 'reporter' || DEFS[st.op]?.type === 'boolean') && !(allowLoneReporter && out.length === 0 && is('}'))) err('a reporter (eval) can only stand alone in its own script { }', tk);
      if (!st || typeof st !== 'object') err('eval() needs a reporter block', tk);
      out.push(st); }
    eat('}'); return out;
  }
  function parseStmt() { enter(); try { return parseStmt2(); } finally { depth--; } }
  function parseStmt2() {
    const tk = eat('id');
    if (tk.v === 'eval') { const a = parseArgs(); return a[0]; }
    if (customs.has(tk.v) && !KW.has(tk.v)) return { op: 'call', name: tk.v, args: parseArgs() };
    const defs = (KW.get(tk.v) || []).filter(d => d.type !== 'reporter' && d.type !== 'boolean' && d.type !== 'hat');
    if (!defs.length) err(`unknown block '${tk.v}'`, tk);
    const d = defs[0];
    let args;
    if (d.type === 'c' || d.type === 'cc') {
      // C-blocks accept both  repeat(10) { }  and  if touching("edge") and x > 3 { }
      const save = p; let okParen = false;
      if (is('(')) { try { args = parseArgs(); okParen = is('{'); } catch (e) { okParen = false; } }
      if (!okParen) { p = save; args = []; if (!is('{')) { do { args.push(parseExpr(0)); } while (is(',') && eat(',')); } }
    } else args = parseArgs();
    if (tk.v === 'if') {
      const body = parseBody(); let body2 = null;
      if (is('id', 'else')) { p++; if (is('id', 'if')) body2 = [parseStmt()]; else body2 = parseBody(); }
      const b = fill(DEFS[body2 ? 'ct_ifelse' : 'ct_if'], args, tk); b.body = body; if (body2) b.body2 = body2; return b;
    }
    const b = fill(d, args, tk);
    if (d.type === 'c') b.body = parseBody();
    return b;
  }
  function parseScript() {
    const tk = peek();
    if (tk.t !== 'id') err(`expected a script (e.g. on_ignite { ... }) but found ${tk.v ?? tk.t}`);
    if (tk.v === 'define') {
      p++; let warp = false; if (is('!')) { p++; warp = true; }
      const name = eat('id').v; eat('('); const params = [];
      if (!is(')')) { do { params.push(eat('id').v); } while (is(',') && eat(',')); }
      eat(')'); return { blocks: [{ op: 'define', name, params, warp, args: [] }, ...parseBody()] };
    }
    if (tk.v === 'script') { p++; return { blocks: parseBody(true) }; }
    const hat = (KW.get(tk.v) || []).find(d => d.type === 'hat');
    if (hat) { p++; const b = fill(hat, parseArgs(), tk); return { blocks: [b, ...parseBody()] }; }
    err(`'${tk.v}' cannot start a script — use a hat like on_ignite { }, define name() { } or script { }`);
  }
  const scripts = [];
  while (!is('eof')) scripts.push(parseScript());
  return validateScripts(scripts);   // same allow-list / reserved-name / size checks as JSON import and the API
}

// Collect names for syntax highlighting / docs
export const KEYWORDS = [...KW.keys(), 'define', 'script', 'else', 'and', 'or', 'not', 'eval', 'param'];
export function highlight(src) {
  const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  return src.replace(/(\/\/[^\n]*)|("(?:\\.|[^"\\])*"?)|(@@?(?:[A-Za-z_]\w*|"(?:\\.|[^"\\])*"?))|(\b\d+(?:\.\d+)?\b)|([A-Za-z_]\w*)|([&<>])/g, (m, c, s, v, n, id, e) => {
    if (c) return `<span class="tk-c">${esc(c)}</span>`; if (s) return `<span class="tk-s">${esc(s)}</span>`;
    if (v) return `<span class="tk-v">${esc(v)}</span>`; if (n) return `<span class="tk-n">${n}</span>`;
    if (id) { if (id.startsWith('on_') || id === 'define' || id === 'script') return `<span class="tk-h">${id}</span>`; if (KW.has(id) || ['else', 'and', 'or', 'not'].includes(id)) return `<span class="tk-k">${id}</span>`; return id; }
    return esc(e);
  });
}
